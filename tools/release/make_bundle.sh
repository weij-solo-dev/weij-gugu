#!/usr/bin/env bash
# make_bundle.sh — build the firmware and pack a self-contained flashing bundle, dist/gugu-<version>.zip,
# for a machine that has no ESP-IDF: the bundle carries the binaries, their flash offsets (read from the
# build's flasher_args.json, never hard-coded), the serial tools, and flash.sh / console.sh / monitor.sh,
# which bootstrap esptool + pyserial into a private virtualenv on first use.
#
#   tools/release/make_bundle.sh              # idf.py build, then pack
#   tools/release/make_bundle.sh --no-build   # pack what build/ already holds
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
if [ "${1:-}" != "--no-build" ]; then
    if [ -z "${IDF_PATH:-}" ]; then . "$HOME/esp/esp-idf/export.sh" >/dev/null; fi
    idf.py build
fi
[ -f build/flasher_args.json ] || { echo "build/flasher_args.json missing: run idf.py build first" >&2; exit 1; }

VERSION="$(git describe --always --dirty 2>/dev/null || echo nogit)-$(date +%Y%m%d-%H%M)"
OUT="dist/gugu-$VERSION"
rm -rf "$OUT"
mkdir -p "$OUT/bin" "$OUT/tools"

# Copy every image idf.py would flash and write the manifest flash.sh sources.
python3 - "$OUT" "$VERSION" <<'EOF'
import json, os, shutil, sys
out, version = sys.argv[1], sys.argv[2]
args = json.load(open('build/flasher_args.json'))
settings, files = args['flash_settings'], args['flash_files']
images, app = [], None
for off in sorted(files, key=lambda o: int(o, 16)):
    src = os.path.join('build', files[off])
    name = os.path.basename(src)
    shutil.copy(src, os.path.join(out, 'bin', name))
    images.append(f'{off} bin/{name}')
    if name == 'gugu.bin': app = f'{off} bin/{name}'
assert app, 'gugu.bin not among the flash files'
with open(os.path.join(out, 'flash_manifest.sh'), 'w') as f:
    f.write('# Generated by tools/release/make_bundle.sh — offsets come from build/flasher_args.json.\n')
    f.write(f'VERSION="{version}"\n')
    f.write(f'CHIP="{args["extra_esptool_args"]["chip"]}"\n')
    f.write(f'FLASH_MODE="{settings["flash_mode"]}"\nFLASH_SIZE="{settings["flash_size"]}"\nFLASH_FREQ="{settings["flash_freq"]}"\n')
    f.write(f'IMAGES="{" ".join(images)}"\n')
    f.write(f'APP_IMAGE="{app}"\n')
print('images:', ', '.join(images))
EOF

cp tools/release/bundle/flash.sh tools/release/bundle/console.sh tools/release/bundle/monitor.sh tools/release/bundle/README.md "$OUT/"
cp tools/dev/serial_cmd.py tools/dev/monitor.py "$OUT/tools/"
chmod +x "$OUT"/*.sh
(cd dist && rm -f "gugu-$VERSION.zip" && zip -qr "gugu-$VERSION.zip" "gugu-$VERSION")
echo "bundle: $ROOT/dist/gugu-$VERSION.zip ($(du -h "dist/gugu-$VERSION.zip" | cut -f1))"
